"""
Object storage abstraction for media files.

Keys are generated by the application only (never from user or provider
input) and must match SAFE_KEY. Backends: local filesystem today; S3,
Cloudflare R2 and MinIO can implement the same interface.
"""
import re
from abc import ABC, abstractmethod
from collections.abc import Iterator
from typing import ClassVar

SAFE_KEY = re.compile(r"^[a-z0-9][a-z0-9_\-]*(/[a-z0-9][a-z0-9_\-.]*)*$")
MAX_KEY_LENGTH = 400


class StorageError(Exception):
    """Storage operation failed. Message is safe to store/return."""


class InvalidStorageKeyError(StorageError):
    """Raised for keys that are not generated-safe (e.g. traversal)."""


def validate_key(key: str) -> str:
    if (
        not key
        or len(key) > MAX_KEY_LENGTH
        or ".." in key
        or not SAFE_KEY.match(key)
    ):
        raise InvalidStorageKeyError("Invalid storage key.")
    return key


class MediaStorage(ABC):
    backend_name: ClassVar[str]

    @abstractmethod
    def save(self, key: str, data: bytes, content_type: str) -> None:
        """Store bytes under key (overwrites)."""

    @abstractmethod
    def iter_chunks(self, key: str, chunk_size: int = 64 * 1024) -> Iterator[bytes]:
        """Stream stored bytes."""

    @abstractmethod
    def delete(self, key: str) -> None:
        """Delete key if present."""

    @abstractmethod
    def exists(self, key: str) -> bool:
        """Whether key exists."""
